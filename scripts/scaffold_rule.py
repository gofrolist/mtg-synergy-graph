#: Type tokens that disqualify a scales_with.Valid port from the
#: creature-count axis (those go to the scaling rule instead).
_OTHER_TYPE_TOKENS: frozenset[str] = frozenset(
    {{"Aura", "Equipment", "Enchantment", "Artifact", "Land", "Instant", "Sorcery", "Planeswalker"}}
)

#: Qualifier tokens whose presence routes the port into a more
#: specific sub-cell (Adeline's `attacking`, Marchesa's
#: `counters_GE`, Selvala's `wasUntappedThisTurn`, etc.). Mirrors
#: gap_report._NOTABLE_QUALIFIERS — staying in sync with the auditor's
#: sub-cell discriminators is the rule's correctness invariant.
_QUALIFIER_BLOCKERS: tuple[str, ...] = (
    "attacking", "blocking", "tapped", "untapped", "modified",
    "kicked", "counters_GE", "wasUntapped", "wasCast", "wasDealt",
)


def _creature_count_scaler_gate(port: PortRow) -> bool:
    """True iff ``port`` is a pure creature-count scales_with port.

    Pure = main token Creature, no other type token (Aura / Equipment /
    ...), AND no notable qualifier (attacking / tapped / counters_GE
    / etc.) that would route the port to a different sub-cell.
    """
    if (port.get("port_type") or "").strip() != "scales_with":
        return False
    if (port.get("event_class") or "").strip() != "Valid":
        return False
    vf = port.get("valid_filter") or ""
    if "Creature" not in vf:
        return False
    if any(tok in vf for tok in _OTHER_TYPE_TOKENS):
        return False
    return not any(tok in vf for tok in _QUALIFIER_BLOCKERS)


