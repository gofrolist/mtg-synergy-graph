@dataclass
class ValidationResult:
    """Outcome of post-apply validation. ``passed`` is the AND of all
    individual checks; ``summary`` is a one-paragraph narrative.

    Four orthogonal signals from the orchestrator:

    - ``trivial``: passed everything but contributes no measurable
      hi_syn improvement (zero touched OR fires-but-never-lands OR
      wins offset losses to net zero). Kept on disk but blocked
      from retry.
    - ``harmful``: pre-ship impact check found NEGATIVE net hi_syn
      delta across touched commanders — rule is displacing better
      candidates from top-30. ``passed`` is False; auto-revert.
    - ``marginal``: net positive hi_syn delta but ratio
      sum/touched < 0.1 — under one improvement per ten touched
      commanders, barely above noise. Kept on disk but blocked
      from retry on the same template (don't keep shipping rules
      that barely register).
    """

    passed: bool
    summary: str
    trivial: bool = False
    trivial_reason: str | None = None
    harmful: bool = False
    harmful_reason: str | None = None
    marginal: bool = False
    marginal_reason: str | None = None


def _run(cmd: list[str], cwd: Path) -> subprocess.CompletedProcess:
    """Run a subprocess command and capture stdout+stderr.

    Inputs are hard-coded ``["uv", "run", ...]`` invocations from this
    file — no external/untrusted input flows into ``cmd``. Suppress
    ruff's S603 here because the tainted-input model doesn't apply.
    """
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=False)  # noqa: S603


def _validate(art: ScaffoldArtifacts, allow_ndcg_drop: float) -> ValidationResult:
    """Delegate to ``scripts/_validate_rule.py`` — one subprocess that
    runs pytest + golden + broad + the trivial-impact check.

    Consolidates four ``uv run`` cold starts (~6s of overhead) into one,
    and surfaces the trivial-impact verdict so the caller can record
    rules that pass validation but don't actually move anything.
    """
    result = _run(
        [
            "uv",
            "run",
            "python",
            "scripts/_validate_rule.py",
            "--rule-id",
            art.rule_id,
            "--allow-ndcg-drop",
            str(allow_ndcg_drop),
        ],
        cwd=REPO_ROOT,
    )
    # The orchestrator emits exactly one JSON line on stdout (the last
    # non-blank line), preceded by pytest output and other prints.
    json_line = next(
        (ln for ln in reversed(result.stdout.splitlines()) if ln.strip().startswith("{")),
        None,
    )
    if json_line is None:
        return ValidationResult(
            passed=False,
            summary=(
                f"_validate_rule.py emitted no JSON result "
                f"(exit {result.returncode}).\n\n"
                f"stdout tail:\n{result.stdout[-1500:]}\n"
                f"stderr tail:\n{result.stderr[-500:]}"
            ),
        )
    try:
        payload = json.loads(json_line)
    except json.JSONDecodeError as exc:
        return ValidationResult(
            passed=False,
            summary=f"Could not parse _validate_rule.py output: {exc}\nLine: {json_line[:500]}",
        )
    return ValidationResult(
        passed=bool(payload.get("passed")),
        summary=str(payload.get("summary", "")),
        trivial=bool(payload.get("trivial")),
        trivial_reason=payload.get("trivial_reason"),
        harmful=bool(payload.get("harmful")),
        harmful_reason=payload.get("harmful_reason"),
        marginal=bool(payload.get("marginal")),
        marginal_reason=payload.get("marginal_reason"),
    )


