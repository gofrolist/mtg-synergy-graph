def _ensure_generated_init() -> None:
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    init = GENERATED_DIR / "__init__.py"
    if not init.exists():
        init.write_text(
            '"""Auto-generated complement rules.\n\nProduced by `scripts/scaffold_rule.py` from auditor proposals.\n"""\n'
        )


def _patch_core(art: ScaffoldArtifacts) -> bool:
    """Insert the import + dispatch line into core.py. Idempotent."""
    src = CORE_PATH.read_text()
    if art.core_import_line in src:
        return False

    # Insert import as its own line right after the existing `from .utility
    # import (...)` block. Using re.DOTALL so the lazy ``[\s\S]+?`` actually
    # matches across newlines.
    util_import_block = re.search(r"from \.utility import \([\s\S]+?\)\n", src)
    if util_import_block is None:
        return False
    block = util_import_block.group(0)
    src = src.replace(block, block + art.core_import_line + "\n", 1)

    # Insert dispatch line into _card_attr_complements after the last
    # registered helper call (use damage_doubler_synergy as the anchor —
    # it's the most recently added port-level rule before the new ones).
    anchor = "        out.extend(_find_damage_doubler_synergy(conn, cmdr_ports, cmdr_set))"
    src = src.replace(anchor, anchor + "\n" + art.core_dispatch_line, 1)
    CORE_PATH.write_text(src)
    return True


def _patch_registry(art: ScaffoldArtifacts) -> bool:
    src = REGISTRY_PATH.read_text()
    if art.registry_import_line in src:
        return False

    # Insert import after the existing `from .core import` block.
    src = src.replace(
        "from .core import COMPLEMENT_RULES, PortRow",
        f"from .core import COMPLEMENT_RULES, PortRow\n{art.registry_import_line}",
        1,
    )
    # Insert RuleGate entry at the END of _CARD_ATTR_GATES tuple.
    src = src.replace(
        '    RuleGate("aura_equipment_support", _aura_equipment_support_gate),\n)',
        f'    RuleGate("aura_equipment_support", _aura_equipment_support_gate),\n{art.registry_gate_line}\n)',
        1,
    )
    REGISTRY_PATH.write_text(src)
    return True


def _patch_scorer(art: ScaffoldArtifacts) -> bool:
    src = SCORER_PATH.read_text()
    if f'"{art.rule_id}":' in src:
        return False

    # Insert bucket entry into _RULE_TO_BUCKET.
    src = src.replace(
        '    "peer_evasion_tribal": "port_match",\n}',
        f'    "peer_evasion_tribal": "port_match",\n{art.scorer_bucket_entry}\n}}',
        1,
    )
    # Insert multiplier entry — append to end of _RULE_QUALITY_MULTIPLIER.
    src = src.replace(
        '    "peer_evasion_tribal": 2.0,\n}',
        f'    "peer_evasion_tribal": 2.0,\n{art.scorer_multiplier_entry}\n}}',
        1,
    )
    SCORER_PATH.write_text(src)
    return True


def apply_artifacts(art: ScaffoldArtifacts) -> dict[str, bool]:
    _ensure_generated_init()
    art.helper_module_path.write_text(art.helper_module_src)
    art.test_module_path.write_text(art.test_module_src)
    return {
        "helper_module": True,
        "test_module": True,
        "core_patched": _patch_core(art),
        "registry_patched": _patch_registry(art),
        "scorer_patched": _patch_scorer(art),
    }


