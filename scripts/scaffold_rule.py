#: Type tokens that disqualify a scales_with.Valid port from the
#: creature-count axis (those go to the scaling rule instead).
_OTHER_TYPE_TOKENS: frozenset[str] = frozenset(
    {{"Aura", "Equipment", "Enchantment", "Artifact", "Land", "Instant", "Sorcery", "Planeswalker"}}
)

#: Qualifier tokens whose presence routes the port into a more
#: specific sub-cell (Adeline's `attacking`, Marchesa's
#: `counters_GE`, Selvala's `wasUntappedThisTurn`, etc.). Mirrors
#: gap_report._NOTABLE_QUALIFIERS — staying in sync with the auditor's
#: sub-cell discriminators is the rule's correctness invariant.
_QUALIFIER_BLOCKERS: tuple[str, ...] = (
    "attacking", "blocking", "tapped", "untapped", "modified",
    "kicked", "counters_GE", "wasUntapped", "wasCast", "wasDealt",
)


def _creature_count_scaler_gate(port: PortRow) -> bool:
    """True iff ``port`` is a pure creature-count scales_with port.

    Pure = main token Creature, no other type token (Aura / Equipment /
    ...), AND no notable qualifier (attacking / tapped / counters_GE
    / etc.) that would route the port to a different sub-cell.
    """
    if (port.get("port_type") or "").strip() != "scales_with":
        return False
    if (port.get("event_class") or "").strip() != "Valid":
        return False
    vf = port.get("valid_filter") or ""
    if "Creature" not in vf:
        return False
    if any(tok in vf for tok in _OTHER_TYPE_TOKENS):
        return False
    return not any(tok in vf for tok in _QUALIFIER_BLOCKERS)


def _find_creature_count_scaler(
    conn: sqlite3.Connection,
    cmdr_ports: list[PortRow],
    cmdr_set: set[str],
) -> list[PortComplement]:
    """Surface go-wide payoffs for commanders that scale with creature count.

    TODO: refine the mechanical hypothesis after running validation
    against a few exemplar commanders.
    """
    if not any(_creature_count_scaler_gate(p) for p in cmdr_ports):
        return []

    # Tier 1: anthems on Creature.YouCtrl with AddPower / AddToughness /
    # AddKeyword. Highest priority — narrow pool, direct payoff.
    anthem_set: set[str] = {{
        row["card_name"]
        for row in conn.execute(
            "SELECT DISTINCT card_name FROM card_ports "
            "WHERE port_type = 'static' AND event_class = 'Continuous' "
            "AND raw_line LIKE '%Creature.YouCtrl%' "
            "AND (raw_line LIKE '%AddPower%' OR raw_line LIKE '%AddToughness%' OR raw_line LIKE '%AddKeyword%')"
        )
    }}

    # Tier 2: token producers (creature tokens via TokenScript).
    token_set: set[str] = {{
        row["card_name"]
        for row in conn.execute(
            "SELECT DISTINCT cp.card_name FROM card_ports cp "
            "JOIN cards c ON c.name = cp.card_name "
            "WHERE cp.port_type = 'effect' AND cp.event_class = 'Token' "
            "AND cp.raw_line LIKE '%TokenScript%' "
            "AND c.legal_commander = 1"
        )
    }}

    # Tier 3: other creature-count scalers (stack IDF — these are
    # cards that themselves count creatures, like Beastmaster
    # Ascension).
    scaler_set: set[str] = {{
        row["card_name"]
        for row in conn.execute(
            "SELECT DISTINCT card_name FROM card_ports "
            "WHERE port_type = 'scales_with' AND event_class = 'Valid' "
            "AND valid_filter LIKE '%Creature%'"
        )
    }}

