"""Scaffold a new complement rule from a gap_report.py proposal.

End-to-end automation of the rule-writing step. Reads the top
proposal from the auditor (or accepts an explicit signature), looks
up the matching template in the generator catalog, and emits:

  - ``src/mtg_synergy_graph/complement_rules/generated/<rule_id>.py``
    A self-contained module with the helper function AND the gate
    predicate. Importable + callable as-is.
  - ``tests/test_generated_<rule_id>.py``
    Test class with gate rejection, per-tier match, dedup, and
    rule_id assertions.
  - stdout: integration patches (which lines to add to core.py /
    registry.py / universal_scorer.py).

With ``--apply``, the patches are automatically written to the
target files. Without ``--apply`` (default), the patches are
printed for manual review.

Generators in the catalog map 1:1 to templates in
``scripts/gap_report.py``. Adding a new template = adding a new
generator function here.
"""

