_KEYWORD_SANITIZE_RE = re.compile(r"[^a-z0-9]+")


def _sanitize_for_identifier(name: str) -> str:
    """Coerce a keyword (e.g. ``Doctor's``, ``Ward:2``) into a Python
    identifier-safe slug (``doctors``, ``ward_2``).
    """
    s = _KEYWORD_SANITIZE_RE.sub("_", name.lower()).strip("_")
    return s or "unknown"


