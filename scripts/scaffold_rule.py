def _refresh_registry() -> None:
    """Reload the runtime registry module and propagate the fresh
    ``RULE_GATES`` tuple into gap_report's namespace.

    Required between walk iterations: gap_report.RULE_GATES is bound
    at import time, so newly-registered gates from a freshly-shipped
    rule are invisible to the picker on the next iteration without
    explicit reload. Without this, the walker re-picks the same
    signature every iteration and the patcher silently no-ops on
    re-application.
    """
    from mtg_synergy_graph.complement_rules import registry

    importlib.reload(registry)
    import gap_report

    gap_report.RULE_GATES = registry.RULE_GATES


def _attempt_one(
    art: ScaffoldArtifacts,
    template_name: str,
    signature: tuple[str, str, str],
    *,
    validate: bool,
    allow_ndcg_drop: float,
    force: bool,
) -> str:
    """Run one apply+validate cycle. Returns the outcome string
    (``"passed"``, ``"reverted"``, ``"skipped"``).

    Records the outcome to the attempt log on every code path. Also
    handles the known-bad pre-check (returns ``"skipped"`` without
    touching files).
    """
    blocked, prior_reason = is_known_bad(template_name, art.rule_id)
    if blocked and not force:
        print(
            f"\n[SKIPPED] (template={template_name}, rule_id={art.rule_id}) "
            f"was previously reverted:\n  {prior_reason[:200]}",
            file=sys.stderr,
        )
        record_attempt(
            AttemptRecord(
                timestamp=now_iso(),
                rule_id=art.rule_id,
                template=template_name,
                signature=signature,
                outcome="skipped",
                reason=f"prior revert: {prior_reason[:150]}",
            )
        )
        return "skipped"

    t_blocked, t_reason = is_template_blocked(template_name)
    if t_blocked and not force:
        print(
            f"\n[SKIPPED] template `{template_name}` is blocked: {t_reason}",
            file=sys.stderr,
        )
        record_attempt(
            AttemptRecord(
                timestamp=now_iso(),
                rule_id=art.rule_id,
                template=template_name,
                signature=signature,
                outcome="skipped",
                reason=f"template blocked: {t_reason}",
            )
        )
        return "skipped"

    snapshot = _capture_state(_affected_paths(art)) if validate else None
    results = apply_artifacts(art)
    print(f"\nApplied artifacts for `{art.rule_id}`:", file=sys.stderr)
    for k, v in results.items():
        status = "wrote" if v else "skipped (already present)"
        print(f"  {k}: {status}", file=sys.stderr)

    files_touched = tuple(str(p.relative_to(REPO_ROOT)) for p in _affected_paths(art))

    if not (validate and snapshot is not None):
        print("\n(Skipped validation — re-run pytest + golden_set_track manually)", file=sys.stderr)
        return "passed"  # No validation means we trust the user; treat as passed.

    print("\nValidating (pytest + golden NDCG + broad NDCG + impact check)...", file=sys.stderr)
    result = _validate(art, allow_ndcg_drop=allow_ndcg_drop)
    if result.passed and result.trivial:
        # Kept on disk (rule is mechanically correct, no regressions),
        # but flagged as trivial so the walk loop won't keep proposing
        # the same template/signature pair without --force.
        print(f"\n[TRIVIAL] {result.summary}", file=sys.stderr)
        print(f"  reason: {result.trivial_reason}", file=sys.stderr)
        record_attempt(
            AttemptRecord(
                timestamp=now_iso(),
                rule_id=art.rule_id,
                template=template_name,
                signature=signature,
                outcome="trivial",
                reason=(result.trivial_reason or "rule activates on no validated commander"),
                files_touched=files_touched,
            )
        )
        return "trivial"
    if result.passed and result.marginal:
        # Kept on disk (mechanically correct + net positive) but signal
        # is too weak to justify continuing on this template axis. Same
        # blocking treatment as trivial.
        print(f"\n[MARGINAL] {result.summary}", file=sys.stderr)
        print(f"  reason: {result.marginal_reason}", file=sys.stderr)
        record_attempt(
            AttemptRecord(
                timestamp=now_iso(),
                rule_id=art.rule_id,
                template=template_name,
                signature=signature,
                outcome="marginal",
                reason=(result.marginal_reason or "barely-positive impact"),
                files_touched=files_touched,
            )
        )
        return "marginal"
    if result.passed:
        print(f"\n[PASS] {result.summary}", file=sys.stderr)
        record_attempt(
            AttemptRecord(
                timestamp=now_iso(),
                rule_id=art.rule_id,
                template=template_name,
                signature=signature,
                outcome="passed",
                reason=result.summary,
                files_touched=files_touched,
            )
        )
        return "passed"

    tag = "HARMFUL" if result.harmful else "FAIL"
    print(f"\n[{tag}] {result.summary}", file=sys.stderr)
    if result.harmful_reason:
        print(f"  reason: {result.harmful_reason}", file=sys.stderr)
    _restore_state(snapshot)
    print("Reverted all changes for this attempt.", file=sys.stderr)
    reason = result.harmful_reason or result.summary
    record_attempt(
        AttemptRecord(
            timestamp=now_iso(),
            rule_id=art.rule_id,
            template=template_name,
            signature=signature,
            outcome="reverted",
            reason=(f"harmful: {reason}" if result.harmful else reason)[:600],
            files_touched=files_touched,
        )
    )
    return "reverted"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", type=Path, default=Path("data/synergy.db"))
    parser.add_argument("--template", help="explicit template to scaffold (default: top auditor proposal)")
    parser.add_argument("--apply", action="store_true", help="write files AND patch integration points")
    parser.add_argument(
        "--no-validate",
        dest="validate",
        action="store_false",
        default=True,
        help="(use with --apply) skip post-apply validation. Default: validate and auto-revert on failure.",
    )
    parser.add_argument(
        "--allow-ndcg-drop",
        type=float,
        default=0.0,
        help="(use with --apply) maximum tolerated golden NDCG drop. Default 0.0 = revert on any regression.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="(use with --apply) override the attempt-log block on a "
        "(template, rule_id) previously reverted. Use after refining "
        "the template and expecting a different outcome.",
    )
    parser.add_argument(
        "--walk",
        type=int,
        default=1,
        help="(use with --apply) drain the queue: try N proposals in a "
        "row, picking the next one after each (skipping known-bad). "
        "Default 1 = single attempt, current behavior. The picker "
        "re-scans the universe each iteration so freshly-shipped "
        "rules update the queue.",
    )
    parser.add_argument(
        "--show-template-stats",
        action="store_true",
        help="Print per-template attempt statistics from the attempt log "
        "(passed/trivial/reverted/skipped + smoothed pass rate + block "
        "status) and exit. Useful for understanding which generators "
        "are paying off and which are systematically broken.",
    )
    args = parser.parse_args()

    if args.show_template_stats:
        stats = template_stats()
        if not stats:
            print("attempt log is empty — no template statistics yet.")
            return 0
        rows = []
        for t in sorted(stats):
            counts = stats[t]
            rate, fresh = template_pass_rate(t)
            blocked, _ = is_template_blocked(t)
            rows.append(
                (
                    t,
                    counts.get("passed", 0),
                    counts.get("trivial", 0),
                    counts.get("marginal", 0),
                    counts.get("reverted", 0),
                    counts.get("skipped", 0),
                    fresh,
                    rate,
                    "BLOCKED" if blocked else "ok",
                )
            )
        print(
            f"{'template':<35} {'pass':>5} {'triv':>5} {'marg':>5} {'rev':>5} "
            f"{'skip':>5} {'fresh':>6} {'rate':>6}  status"
        )
        print("-" * 86)
        for row in rows:
            print(
                f"{row[0]:<35} {row[1]:>5} {row[2]:>5} {row[3]:>5} {row[4]:>5} "
                f"{row[5]:>5} {row[6]:>6} {row[7]:>6.2f}  {row[8]}"
            )
        return 0

    if args.walk > 1 and not args.apply:
        print("error: --walk requires --apply", file=sys.stderr)
        return 2
    if args.walk > 1 and args.template:
        print("error: --walk can't be combined with --template (walk re-picks each iteration)", file=sys.stderr)
        return 2

    conn = sqlite3.connect(args.db)
    conn.row_factory = sqlite3.Row
    try:
        # Walk mode: drain the queue. Each iteration re-picks (the
        # picker skips known-bad combos), then applies+validates.
        if args.walk > 1:
            counts = {"passed": 0, "reverted": 0, "skipped": 0, "trivial": 0, "marginal": 0}
            shipped: list[str] = []
            for i in range(1, args.walk + 1):
                print(f"\n========== Walk iteration {i}/{args.walk} ==========", file=sys.stderr)
                proposal = _pick_top_proposal(conn)
                if proposal is None:
                    print("Queue exhausted (no more eligible proposals).", file=sys.stderr)
                    break
                print(
                    f"Picked: `{proposal.gap.signature[0]}.{proposal.gap.signature[1]}[{proposal.gap.signature[2] or '*'}]` "
                    f"(reach={proposal.gap.commanders}, template={proposal.template})",
                    file=sys.stderr,
                )
                art = _GENERATORS[proposal.template](proposal)
                outcome = _attempt_one(
                    art,
                    proposal.template,
                    proposal.gap.signature,
                    validate=args.validate,
                    allow_ndcg_drop=args.allow_ndcg_drop,
                    force=args.force,
                )
                counts[outcome] += 1
                if outcome == "passed":
                    shipped.append(art.rule_id)
                # Refresh the in-process registry so the next iteration's
                # picker sees freshly-registered gates (or the absence of
                # ones that were reverted). Without this, the walker
                # re-picks the same signature every iteration.
                _refresh_registry()
            print("\n========== Walk summary ==========", file=sys.stderr)
            print(
                f"  passed:   {counts['passed']}  ({', '.join(shipped) or '—'})",
                file=sys.stderr,
            )
            print(f"  marginal: {counts['marginal']}", file=sys.stderr)
            print(f"  trivial:  {counts['trivial']}", file=sys.stderr)
            print(f"  reverted: {counts['reverted']}", file=sys.stderr)
            print(f"  skipped:  {counts['skipped']}", file=sys.stderr)
            if shipped:
                print(
                    "\nReview the working tree, then commit the shipped rules.",
                    file=sys.stderr,
                )
            return 0 if counts["passed"] > 0 else 1

        # Single-attempt mode (default).
        if args.template:
            if args.template not in _GENERATORS:
                print(f"error: no generator for template '{args.template}'", file=sys.stderr)
                print(f"available: {sorted(_GENERATORS)}", file=sys.stderr)
                return 2
            stub = GapStat(signature=("", "", ""), commanders=0, activations=0, exemplars=(), top_rules=())
            stub_proposal = RuleProposal(
                gap=stub,
                template=args.template,
                rationale="",
                gate_sketch="",
                tier_sketches=(),
                pool_sizes={},
            )
            template_name = args.template
            signature: tuple[str, str, str] = ("", "", "")
            try:
                art = _GENERATORS[args.template](stub_proposal)
            except ValueError as exc:
                # Some templates require concrete signature discriminators
                # (e.g. replacement_stack needs a non-empty event_class +
                # replacement_result). The walk picker feeds these from
                # gap_report; manual --template invocations don't.
                print(
                    f"error: template '{args.template}' rejected stub proposal: {exc}",
                    file=sys.stderr,
                )
                print(
                    "       Use --apply --walk 1 to let the auditor pick a concrete signature.",
                    file=sys.stderr,
                )
                return 2
        else:
            proposal = _pick_top_proposal(conn)
            if proposal is None:
                print("No proposal in the queue matches a registered generator.", file=sys.stderr)
                print(f"Available generators: {sorted(_GENERATORS)}", file=sys.stderr)
                return 1
            print(
                f"Top proposal: `{proposal.gap.signature[0]}.{proposal.gap.signature[1]}[{proposal.gap.signature[2] or '*'}]` "
                f"(reach={proposal.gap.commanders}, template={proposal.template})",
                file=sys.stderr,
            )
            template_name = proposal.template
            signature = proposal.gap.signature
            art = _GENERATORS[proposal.template](proposal)
    finally:
        conn.close()

    if not args.apply:
        _print_integration_steps(art)
        print("\n(Re-run with --apply to write files + patch integration points)")
        return 0

    outcome = _attempt_one(
        art,
        template_name,
        signature,
        validate=args.validate,
        allow_ndcg_drop=args.allow_ndcg_drop,
        force=args.force,
    )
    if outcome == "passed":
        print("\nKept changes. Suggested next: review the diff and commit.", file=sys.stderr)
        return 0
    if outcome == "trivial":
        print(
            "\nKept changes (no regressions), but the rule contributes no "
            "measurable hi_syn improvement on any validated commander. "
            "Either broaden the gate or rethink the template hypothesis.",
            file=sys.stderr,
        )
        return 1
    if outcome == "marginal":
        print(
            "\nKept changes (mechanically positive) but signal is barely above "
            "noise (sum_Δhi_syn / touched < 0.1). Consider tightening the "
            "gate to focus on the archetype where the rule actually helps.",
            file=sys.stderr,
        )
        return 1
    if outcome == "reverted":
        print(
            "\nRefine the template (QUALIFIER_BLOCKERS, multiplier, tier "
            "choices) in scripts/scaffold_rule.py and re-run.",
            file=sys.stderr,
        )
        return 1
    # outcome == "skipped"
    print(
        "\nRefine the template in scripts/scaffold_rule.py "
        "(_QUALIFIER_BLOCKERS, multiplier, tier choices), then re-run "
        "with --force.",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
