def _add_card(conn, name, types="Creature"):
    conn.execute("INSERT OR IGNORE INTO cards (name, types) VALUES (?, ?)", (name, types))


def _add_port(conn, card_name, **kwargs):
    _add_card(conn, card_name)
    cols = ["card_name"] + list(kwargs.keys())
    vals = [card_name] + list(kwargs.values())
    placeholders = ",".join("?" * len(cols))
    conn.execute(f"INSERT INTO card_ports ({','.join(cols)}) VALUES ({placeholders})", vals)


