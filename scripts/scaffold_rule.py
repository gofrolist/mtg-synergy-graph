def _patch_core(art: ScaffoldArtifacts) -> bool:
    """Insert the import + dispatch line into core.py. Idempotent."""
    src = CORE_PATH.read_text()
    if art.core_import_line in src:
        return False

    # Insert import as its own line right after the existing `from .utility
    # import (...)` block. Using re.DOTALL so the lazy ``[\s\S]+?`` actually
    # matches across newlines.
    util_import_block = re.search(r"from \.utility import \([\s\S]+?\)\n", src)
    if util_import_block is None:
        return False
    block = util_import_block.group(0)
    src = src.replace(block, block + art.core_import_line + "\n", 1)

    # Insert dispatch line into _card_attr_complements after the last
    # registered helper call (use damage_doubler_synergy as the anchor —
    # it's the most recently added port-level rule before the new ones).
    anchor = "        out.extend(_find_damage_doubler_synergy(conn, cmdr_ports, cmdr_set))"
    src = src.replace(anchor, anchor + "\n" + art.core_dispatch_line, 1)
    CORE_PATH.write_text(src)
    return True


def _insert_before_container_close(src: str, name: str, entry: str, open_char: str, close_char: str) -> str | None:
    """Insert ``entry`` as the last line of a container literal named
    ``name`` (a dict, tuple, or list). Returns the modified source, or
    ``None`` if the container can't be located.

    Walks the source brace-by-brace from the container's opening
    delimiter, tracking nesting, until the matching close is found.
    Robust against any number of pre-existing entries — anchors that
    reference a specific previous entry break after each new
    insertion, this approach doesn't.
    """
    match = re.search(rf"\b{re.escape(name)}\b[^=]*=\s*{re.escape(open_char)}", src)
    if match is None:
        return None
    depth = 0
    i = match.end() - 1  # position of the opening delimiter
    while i < len(src):
        c = src[i]
        if c == open_char:
            depth += 1
        elif c == close_char:
            depth -= 1
            if depth == 0:
                # i points at the matching close. Insert entry on its
                # own line just before the line containing the close.
                line_start = src.rfind("\n", 0, i) + 1
                return src[:line_start] + entry + "\n" + src[line_start:]
        i += 1
    return None


def _patch_registry(art: ScaffoldArtifacts) -> bool:
    src = REGISTRY_PATH.read_text()
    if art.registry_import_line in src:
        return False

    # Insert import after the existing `from .core import` block.
    src = src.replace(
        "from .core import COMPLEMENT_RULES, PortRow",
        f"from .core import COMPLEMENT_RULES, PortRow\n{art.registry_import_line}",
        1,
    )
    # Insert RuleGate entry at the END of the _CARD_ATTR_GATES tuple
    # — using the brace-walking helper so subsequent insertions don't
    # depend on a specific previous entry being the last one.
    new_src = _insert_before_container_close(src, "_CARD_ATTR_GATES", art.registry_gate_line, "(", ")")
    if new_src is None:
        return False
    REGISTRY_PATH.write_text(new_src)
    return True


def _patch_scorer(art: ScaffoldArtifacts) -> bool:
    src = SCORER_PATH.read_text()
    if f'"{art.rule_id}":' in src:
        return False

    # Same brace-walking insertion for both dicts.
    new_src = _insert_before_container_close(src, "_RULE_TO_BUCKET", art.scorer_bucket_entry, "{", "}")
    if new_src is None:
        return False
    new_src = _insert_before_container_close(new_src, "_RULE_QUALITY_MULTIPLIER", art.scorer_multiplier_entry, "{", "}")
    if new_src is None:
        return False
    SCORER_PATH.write_text(new_src)
    return True


def apply_artifacts(art: ScaffoldArtifacts) -> dict[str, bool]:
    _ensure_generated_init()
    art.helper_module_path.write_text(art.helper_module_src)
    art.test_module_path.write_text(art.test_module_src)
    return {
        "helper_module": True,
        "test_module": True,
        "core_patched": _patch_core(art),
        "registry_patched": _patch_registry(art),
        "scorer_patched": _patch_scorer(art),
    }


