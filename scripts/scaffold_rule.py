def _pick_top_proposal(conn: sqlite3.Connection) -> RuleProposal | None:
    """Walk the auditor's queue, return the first proposal that:
    - has a registered generator AND
    - is not known-bad (i.e., its (template, rule_id) wasn't previously
      reverted in the attempt log).

    The known-bad skip is what makes the autonomy loop converge: every
    failed attempt is recorded, and subsequent runs walk past it to
    the next viable candidate. Pass ``--force`` to override at the
    apply stage.
    """
    commanders = _commander_names(conn)
    stats = _scan_universe(conn, commanders)
    eligible = [s for s in stats if s.activation_rate < 1.0]
    eligible.sort(key=lambda s: (-s.impact, -s.commanders, s.signature))
    for gap in eligible:
        prop = _propose(gap, conn)
        if prop is None or prop.template not in _GENERATORS:
            continue
        try:
            art = _GENERATORS[prop.template](prop)
        except Exception:  # noqa: S112  (skip generator errors and try the next eligible proposal)
            continue
        blocked, _ = is_known_bad(prop.template, art.rule_id)
        if blocked:
            continue
        return prop
    return None


def _print_integration_steps(art: ScaffoldArtifacts) -> None:
    print(f"\n=== Integration plan for `{art.rule_id}` ===")
    print("\nGenerated files:")
    print(f"  {art.helper_module_path.relative_to(REPO_ROOT)}")
    print(f"  {art.test_module_path.relative_to(REPO_ROOT)}")
    print("\ncomplement_rules/core.py:")
    print(f"  + {art.core_import_line}")
    print(f"  + {art.core_dispatch_line.lstrip()}")
    print("\ncomplement_rules/registry.py:")
    print(f"  + {art.registry_import_line}")
    print(f"  + (in _CARD_ATTR_GATES tuple) {art.registry_gate_line.lstrip()}")
    print("\nuniversal_scorer.py:")
    print(f"  + (in _RULE_TO_BUCKET) {art.scorer_bucket_entry.lstrip()}")
    print(f"  + (in _RULE_QUALITY_MULTIPLIER) {art.scorer_multiplier_entry.splitlines()[-1].lstrip()}")
    print("\nValidate:")
    print(f"  uv run pytest {art.test_module_path.relative_to(REPO_ROOT)} -v")
    print("  uv run python scripts/golden_set_track.py --baseline tests/fixtures/golden_set_run.json")
    print("  uv run python scripts/gap_report.py  # confirm cell drops out of queue")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", type=Path, default=Path("data/synergy.db"))
    parser.add_argument("--template", help="explicit template to scaffold (default: top auditor proposal)")
    parser.add_argument("--apply", action="store_true", help="write files AND patch integration points")
    parser.add_argument(
        "--no-validate",
        dest="validate",
        action="store_false",
        default=True,
        help="(use with --apply) skip post-apply validation. Default: validate and auto-revert on failure.",
    )
    parser.add_argument(
        "--allow-ndcg-drop",
        type=float,
        default=0.0,
        help="(use with --apply) maximum tolerated golden NDCG drop. Default 0.0 = revert on any regression.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="(use with --apply) override the attempt-log block on a "
        "(template, rule_id) previously reverted. Use after refining "
        "the template and expecting a different outcome.",
    )
    args = parser.parse_args()

    conn = sqlite3.connect(args.db)
    conn.row_factory = sqlite3.Row
    try:
        if args.template:
            if args.template not in _GENERATORS:
                print(f"error: no generator for template '{args.template}'", file=sys.stderr)
                print(f"available: {sorted(_GENERATORS)}", file=sys.stderr)
                return 2
            # Build a synthetic proposal from a stub gap.
            stub = GapStat(signature=("", "", ""), commanders=0, activations=0, exemplars=(), top_rules=())
            stub_proposal = RuleProposal(
                gap=stub,
                template=args.template,
                rationale="",
                gate_sketch="",
                tier_sketches=(),
                pool_sizes={},
            )
            template_name = args.template
            signature = ("", "", "")
            art = _GENERATORS[args.template](stub_proposal)
        else:
            proposal = _pick_top_proposal(conn)
            if proposal is None:
                print("No proposal in the queue matches a registered generator.", file=sys.stderr)
                print(f"Available generators: {sorted(_GENERATORS)}", file=sys.stderr)
                return 1
            print(
                f"Top proposal: `{proposal.gap.signature[0]}.{proposal.gap.signature[1]}[{proposal.gap.signature[2] or '*'}]` "
                f"(reach={proposal.gap.commanders}, template={proposal.template})",
                file=sys.stderr,
            )
            template_name = proposal.template
            signature = proposal.gap.signature
            art = _GENERATORS[proposal.template](proposal)
    finally:
        conn.close()

    if args.apply:
        # Learning loop: refuse to retry a (template, rule_id) that
        # was previously reverted, unless --force overrides. Records
        # a "skipped" attempt so the log accumulates context.
        blocked, prior_reason = is_known_bad(template_name, art.rule_id)
        if blocked and not args.force:
            print(
                f"\n[SKIPPED] (template={template_name}, rule_id={art.rule_id}) "
                f"was previously reverted:\n  {prior_reason[:200]}",
                file=sys.stderr,
            )
            record_attempt(
                AttemptRecord(
                    timestamp=now_iso(),
                    rule_id=art.rule_id,
                    template=template_name,
                    signature=signature,
                    outcome="skipped",
                    reason=f"prior revert: {prior_reason[:150]}",
                )
            )
            print(
                "\nRefine the template in scripts/scaffold_rule.py "
                "(_QUALIFIER_BLOCKERS, multiplier, tier choices), "
                "then re-run with --force.",
                file=sys.stderr,
            )
            return 1

        snapshot = _capture_state(_affected_paths(art)) if args.validate else None
        results = apply_artifacts(art)
        print(f"\nApplied artifacts for `{art.rule_id}`:", file=sys.stderr)
        for k, v in results.items():
            status = "wrote" if v else "skipped (already present)"
            print(f"  {k}: {status}", file=sys.stderr)

        files_touched = tuple(str(p.relative_to(REPO_ROOT)) for p in _affected_paths(art))

        if args.validate and snapshot is not None:
            print("\nValidating (pytest + golden NDCG)...", file=sys.stderr)
            result = _validate(art, allow_ndcg_drop=args.allow_ndcg_drop)
            if result.passed:
                print(f"\n[PASS] {result.summary}", file=sys.stderr)
                print("\nKept changes. Suggested next: review the diff and commit.", file=sys.stderr)
                record_attempt(
                    AttemptRecord(
                        timestamp=now_iso(),
                        rule_id=art.rule_id,
                        template=template_name,
                        signature=signature,
                        outcome="passed",
                        reason=result.summary,
                        files_touched=files_touched,
                    )
                )
            else:
                print(f"\n[FAIL] {result.summary}", file=sys.stderr)
                _restore_state(snapshot)
                print(
                    "\nReverted all changes. Refine the template "
                    "(QUALIFIER_BLOCKERS, multiplier, tier choices) in "
                    "scripts/scaffold_rule.py and re-run.",
                    file=sys.stderr,
                )
                record_attempt(
                    AttemptRecord(
                        timestamp=now_iso(),
                        rule_id=art.rule_id,
                        template=template_name,
                        signature=signature,
                        outcome="reverted",
                        reason=result.summary[:600],
                        files_touched=files_touched,
                    )
                )
                return 1
        else:
            print("\n(Skipped validation — re-run pytest + golden_set_track manually)", file=sys.stderr)
    else:
        _print_integration_steps(art)
        print("\n(Re-run with --apply to write files + patch integration points)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
